#!/bin/sh
# Build the mihomo core + tun-helper for the mono-repo layout.
#
# Source of truth for the custom QNX code is core/ (backend/helper/tun-helper +
# codec). The mihomo module and its 7 forked dependency overrides are NOT
# vendored here (see docs/REFACTOR-PLAN.md, stage 0c); they are referenced from
# an external checkout via BB10_MIHOMO_SRC. mihomo/go.mod pins the overrides by
# absolute path, so they resolve wherever that checkout lives.
#
# The bb10_real_tun tag adds the QNX TUN backend, dormant unless a config enables
# tun AND the process has BB10_TUN_EXPERIMENT=1; proxy mode sets neither.
set -eu
REPO=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
RESEARCH=${BB10_PROXY_RESEARCH:-"$HOME/bb10-passport/vpn-research"}
MIHOMO_SRC=${BB10_MIHOMO_SRC:-"$REPO/mihomo/upstream"}
GO="$RESEARCH/toolchain/extracted/go/bin/go"
APP="$REPO/app"
CORE="$REPO/core"

[ -x "$GO" ] || { echo "Missing QNX Go toolchain at $GO" >&2; exit 1; }
# Reproducible mihomo core source: pinned upstream commit + patches/mihomo.patch,
# regenerated into mihomo/upstream by fetch-mihomo.sh. Only auto-fetch when using
# the in-repo default (an explicit BB10_MIHOMO_SRC must already exist).
if [ ! -d "$MIHOMO_SRC" ]; then
  if [ "$MIHOMO_SRC" = "$REPO/mihomo/upstream" ]; then
    echo "[build-core] mihomo/upstream missing; fetching pinned core via fetch-mihomo.sh ..."
    sh "$REPO/scripts/fetch-mihomo.sh"
  else
    echo "Missing mihomo source at $MIHOMO_SRC (set BB10_MIHOMO_SRC)" >&2; exit 1
  fi
fi
mkdir -p "$APP/build/bin"

# Ensure the reproducible QNX dependency overrides exist (pinned upstream +
# mihomo/patches/, regenerated by apply-patches.sh into mihomo/overrides-upstream).
# Offline by default via the research modcache; falls back to `go mod download`.
OVR="$REPO/mihomo/overrides-upstream"
if [ ! -d "$OVR" ]; then
  echo "[build-core] overrides-upstream missing; regenerating via apply-patches.sh ..."
  BB10_UPSTREAM_MODCACHE="${BB10_UPSTREAM_MODCACHE:-$RESEARCH/toolchain/modcache}" \
    sh "$REPO/scripts/apply-patches.sh"
fi

# Generate the workspace file that ties the local core to the external mihomo.
# Gitignored: it carries absolute paths. The `replace` lines point the 7 QNX
# dependency overrides at the in-repo regenerated tree, taking precedence over the
# legacy absolute-path replaces in $MIHOMO_SRC/go.mod (workspace replaces win), so
# the build is self-contained and reproducible from mihomo/UPSTREAM + patches/.
{
  echo "go 1.26.0"
  echo
  echo "use ."
  echo "use $MIHOMO_SRC"
  echo
  awk -v o="$OVR" '$1=="module"{print "replace "$2" => "o"/"$4}' "$REPO/mihomo/UPSTREAM"
} > "$CORE/go.work"

env_go() {
 GOCACHE="$RESEARCH/toolchain/cache" GOMODCACHE="$RESEARCH/toolchain/modcache" \
 GOTOOLCHAIN=local GOPROXY=off CGO_ENABLED=0 GOOS=qnx GOARCH=arm GOARM=7 "$GO" "$@"
}

echo "[build-core] mihomo ..."
cd "$CORE"
env_go build -tags "no_easytier bb10_real_tun" -trimpath \
 -ldflags '-X github.com/metacubex/mihomo/constant.Version=qnx-vpn-20261115 -X github.com/metacubex/mihomo/constant.BuildTime=research-snapshot' \
 -o "$APP/build/bin/mihomo" github.com/metacubex/mihomo

echo "[build-core] tun-helper ..."
cd "$CORE"
env_go build -trimpath -o "$APP/build/bin/tun-helper" ./tun-helper

echo "[build-core] done:"
ls -la "$APP/build/bin/mihomo" "$APP/build/bin/tun-helper"
